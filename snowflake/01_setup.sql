--Setup the Role as ACCOUNTADMIN
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;

CREATE OR REPLACE DATABASE WALMART_RAW;
USE DATABASE WALMART_RAW;

CREATE OR REPLACE SCHEMA BRONZE; 
CREATE OR REPLACE SCHEMA SILVER;
CREATE OR REPLACE SCHEMA GOLD;

-- ---------------------------------------

-- DROP STORAGE INTEGRATION MALMART_S3_INT;

CREATE OR REPLACE STORAGE INTEGRATION MALMART_S3_INT
TYPE = EXTERNAL_STAGE
STORAGE_PROVIDER = 'S3'
ENABLED = TRUE
STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<ACCOUNT_ID>:role/WalmartProjectSnowflakeLoadRole'
STORAGE_ALLOWED_LOCATIONS = ('s3://<BUCKET_NAME>');

-- DESCRIBE INTEGRATION MALMART_S3_INT

CREATE OR REPLACE STAGE WALMART_RAW.BRONZE.WALMART_S3_STAGE
STORAGE_INTEGRATION = MALMART_S3_INT
URL= 's3://<BUCKET_NAME>';

