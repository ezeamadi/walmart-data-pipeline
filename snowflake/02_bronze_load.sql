
CREATE OR REPLACE TABLE BRONZE.DEPARTMENT
( 
    STORE VARCHAR,
    DEPT VARCHAR,
    DATE VARCHAR,
    WEEKLY_SALES VARCHAR,
    ISHOLIDAY VARCHAR
);

copy into WALMART_RAW.BRONZE.DEPARTMENT (STORE, DEPT, DATE, WEEKLY_SALES, ISHOLIDAY)
from '@WALMART_RAW.BRONZE.WALMART_S3_STAGE/department.csv'
file_format = (
    type = 'CSV'
    field_delimiter = ','
    skip_header = 1
)
ON_ERROR="SKIP_FILE_2%";

SELECT * 
FROM TABLE(VALIDATE(WALMART_RAW.BRONZE.DEPARTMENT, JOB_ID => '_LAST'));

-- SELECT * FROM WALMART_RAW.BRONZE.DEPARTMENT;

SELECT * 
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(
   TABLE_NAME => 'WALMART_RAW.BRONZE.DEPARTMENT', 
   START_TIME => DATEADD(hours, -24, CURRENT_TIMESTAMP())
));

