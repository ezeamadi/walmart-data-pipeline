-- DBT CONNECTIONS 

USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS DBT_ROLE;

-- compute, then the chain down to the data
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE DBT_ROLE;
GRANT USAGE ON DATABASE WALMART_RAW TO ROLE DBT_ROLE;
GRANT USAGE ON SCHEMA WALMART_RAW.BRONZE TO ROLE DBT_ROLE;

-- read Bronzer
GRANT SELECT ON ALL TABLES IN SCHEMA WALMART_RAW.BRONZE TO ROLE DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA WALMART_RAW.BRONZE TO ROLE DBT_ROLE;

-- write to Silver and Gold
GRANT ALL PRIVILEGES ON SCHEMA WALMART_RAW.SILVER TO ROLE DBT_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA WALMART_RAW.GOLD TO ROLE DBT_ROLE;

-- let dbt create its own dev schema
GRANT CREATE SCHEMA ON DATABASE WALMART_RAW TO ROLE DBT_ROLE;

